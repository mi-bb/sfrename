/**
 * @brief  Make icon from Icon struct.
 *
 * @param[in]  ic_name  Name of Icon struct
 * @return     Pixbuf with icon
 */
static GdkPixbuf *
make_icon (const Icon *ic_name)
{
    return gdk_pixbuf_new_from_data (
            ic_name->pixel_data,
            GDK_COLORSPACE_RGB,
            TRUE,
            8,
            ic_name->width,
            ic_name->height,
            ic_name->width * ic_name->bytes_per_pixel,
            NULL,
            NULL
            );
}
